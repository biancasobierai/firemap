create table if not exists public.app_users (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null unique,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  name text not null,
  image text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.extinguishers (
  id bigint generated by default as identity primary key,
  code text unique,
  type text not null,
  location text not null,
  plan_id bigint not null references public.plans(id) on delete restrict,
  x numeric(4, 1) not null default 50,
  y numeric(4, 1) not null default 50,
  expiry date not null,
  next_maintenance date not null default current_date,
  maintenance_pending boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.firemap_assign_extinguisher_code()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.code is null or btrim(new.code) = '' then
    new.code := 'EXT-' || lpad(new.id::text, 3, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists firemap_assign_extinguisher_code on public.extinguishers;
create trigger firemap_assign_extinguisher_code
before insert on public.extinguishers
for each row execute function public.firemap_assign_extinguisher_code();

alter table public.app_users enable row level security;
alter table public.plans enable row level security;
alter table public.extinguishers enable row level security;